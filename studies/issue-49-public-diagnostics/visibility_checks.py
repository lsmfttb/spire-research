def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def available(value):return {'availability':'available','value':value,'source':'synthetic native fixture / sealed public envelope'}

def main():
    start=time.process_time();out=Path(sys.argv[1]);native=json.loads((out/'visibility-native.json').read_text())
    code=subprocess.check_output(['git.exe','-C','D:/DeadlycatCoding/spire-research','show',PIN47+':studies/issue-47-action-preference/adapter.py']).decode()
    adapter=types.ModuleType('visibility_pinned_adapter');sys.modules[adapter.__name__]=adapter;exec(compile(code,'pinned47_adapter','exec'),adapter.__dict__)
    path=Path('/home/lsmft/.cache/issue47-action-preference/inputs/437001.json')
    sources=json.loads(Path('/home/lsmft/.cache/issue47-action-preference/source.json').read_text())['derived_files']
    record=next(x for x in sources if x['owner']==437001);assert sha(path)==record['derived_sha256']
    envelope=json.loads(json.loads(path.read_text())['root']['serialized'])
    state=envelope['public_state']
    def projection(row):
        resources=copy.deepcopy(state['persistent_resources'])
        for field,value in {'current_hp':row['current_hp'],'max_hp':row['max_hp'],'gold':row['gold'],'deck':row['deck'],'potion_count':row['potion_count'],'potion_capacity':row['potion_capacity'],'potion_identities':row['potions']}.items():resources[field]=available(value)
        return {'schema_id':'native-public-projection-v3','screen_identity':available('REWARDS'),
                'visible_act_boss':available(state['visible_act_boss']),
                'visible_map_graph':available(state['map_graph']),'current_map_node':available(state['current_map_node']),
                'immediately_legal_routes':{'availability':'unavailable','reason':'routes only legal at MAP_SCREEN'},
                'persistent_resources':available(resources),'screen_payload':available(row['payload']),
                'candidate_actions':available(row['candidate_actions'])}
    public={};prepared={}
    for name in ['before','take_at_full_inventory','after_discard','after_card_group0','after_potion_take','after_noncombat_use']:
        row=native[name];p=projection(row)
        prepared[name]=adapter.prepare_policy_input(p,row['candidate_actions'])
        public[name]=json.loads(prepared[name].serialized_input)
        assert prototype.normalize(public[name])['facts']['card_reward_groups']
        for i,a in enumerate(row['candidate_actions']):
            assert adapter.resolve_native_action(prepared[name],i,p,row['candidate_actions'])==a
            assert prototype.mapped_action(public[name],i,row['candidate_actions'])==a
    before=public['before'];norm=prototype.normalize(before)
    groups=norm['facts']['card_reward_groups'];assert len(groups)==2
    assert len(prototype.normalize(public['after_discard'])['facts']['card_reward_groups'])==2
    after=prototype.normalize(public['after_card_group0'])['facts']['card_reward_groups'];assert len(after)==1
    assert after[0] in groups
    assert any(c['kind']=='reward_potion' for c in norm['facts']['legal_candidates'])
    discard=next(i for i,o in enumerate(before['legal_options']) if o['action']['kind']=='game_potion_discard')
    def old(data,index):return student47.features(student47.treatment(json.dumps(data),'visible'),index)
    checks={}
    for field in ['other_card','offered_potion']:
        changed=copy.deepcopy(before)
        index=next(i for i,o in enumerate(changed['legal_options']) if o['action']['kind']==('reward_card' if field=='other_card' else 'reward_potion'))
        sem=changed['legal_options'][index]['semantics'];sem['card' if field=='other_card' else 'potion']['id_label']='SYNTHETIC_DIFFERENT_PUBLIC_ID'
